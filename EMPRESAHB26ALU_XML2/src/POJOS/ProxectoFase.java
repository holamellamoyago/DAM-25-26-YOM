package POJOS;

public class ProxectoFase {
    private String proxecto;
    private String nomeFase;
    private String estado;

    public ProxectoFase() {
    }

    public String getProxecto() {
        return proxecto;
    }

    public void setProxecto(String proxecto) {
        this.proxecto = proxecto;
    }

    public String getNomeFase() {
        return nomeFase;
    }

    public void setNomeFase(String fase) {
        this.nomeFase = fase;
    }

    public String getEstado() {
        return estado;
    }

    public void setEstado(String estado) {
        this.estado = estado;
    }

    

}
